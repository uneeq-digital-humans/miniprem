package mergecompose

import (
	"os/exec"
	"strings"
	"testing"
)

// Expectations below were produced by real bash/grep on the same inputs.
func bashGrep(t *testing.T, official, name string) bool {
	t.Helper()
	cmd := exec.Command("bash", "-c", `echo "$1" | grep -q "^$2$"`, "x", official, name)
	return cmd.Run() == nil
}

func TestGrepLineExact(t *testing.T) {
	official := "monitor\nrenny\nweb-ui\nfoo.bar\n"
	official = strings.TrimRight(official, "\n")
	for _, n := range []string{"monitor", "renny", "web-ui", "web", "foo.bar", "fooxbar", "ren.y", "r*", "*", "", "mon[a-z]tor", "mon[^o]tor", "a+b", "(renny)", `renny\.`, "monitor|renny"} {
		if got, want := grepLineExact(official, n), bashGrep(t, official, n); got != want {
			t.Errorf("name %q: go=%v bash=%v", n, got, want)
		}
	}
	if got, want := grepLineExact("", ""), bashGrep(t, "", ""); got != want {
		t.Errorf("empty/empty go=%v bash=%v", got, want)
	}
}

func TestFindConflicts(t *testing.T) {
	got := findConflicts("monitor\nrenny", "api\nrenny\nmonitor\nzzz")
	if strings.Join(got, ",") != "renny,monitor" {
		t.Fatalf("got %v", got)
	}
	if len(findConflicts("monitor", "api")) != 0 {
		t.Fatal("unexpected conflict")
	}
	if got := findConflicts("", ""); len(got) != 1 || got[0] != "" {
		t.Fatalf("empty/empty: %q", got)
	}
}

func TestTailLast(t *testing.T) {
	if tailLast("a\nb\nc d\n") != "c d" || tailLast("x\n") != "x" {
		t.Fatal("tailLast")
	}
}

